import {readFile,writeFile,mkdir} from 'node:fs/promises';
const base=new URL('./',import.meta.url);
const source=(await Promise.all(['core.js','panel.js'].map(f=>readFile(new URL('src/'+f,base),'utf8')))).join('\n');
await mkdir(new URL('dist/',base),{recursive:true});
await writeFile(new URL('dist/Key Lime.jsx',base),'// Key Lime 1.0.1 — EffectCraft ScriptUI panel\n// Generated by node build.mjs. Edit src/ files.\n'+source);
console.log('Built dist/Key Lime.jsx');
